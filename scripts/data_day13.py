def generate_cohort_matrix(transactions):
    # Determine acquisition month for each customer
    customer_cohort = {}
    for tx in transactions:
        cid = tx['customer_id']
        m = tx['month']
        if cid not in customer_cohort or m < customer_cohort[cid]:
            customer_cohort[cid] = m
            
    # Group active customers by cohort and elapsed months
    cohort_sizes = {}
    cohort_matrix = {}
    
    for tx in transactions:
        cid = tx['customer_id']
        c_month = customer_cohort[cid]
