import math

class CustomerLifetimeValueOptimizer:
    def __init__(self, monthly_arpu, gross_margin_pct, monthly_churn_rate, annual_wacc=0.12):
        self.arpu = float(monthly_arpu)
        self.gm = float(gross_margin_pct)
        self.margin = self.arpu * self.gm
        self.churn = float(monthly_churn_rate)
        self.retention = 1.0 - self.churn
        
        # Monthly discount rate: (1 + WACC)^(1/12) - 1
        self.annual_wacc = float(annual_wacc)
        self.monthly_discount = ((1.0 + self.annual_wacc) ** (1.0 / 12.0)) - 1.0
        
    def calculate_simple_clv(self):
        # Naive formula: Margin / Churn
        expected_lifespan_months = (1.0 / self.churn) if self.churn > 0 else 999.0
        clv_simple = self.margin / self.churn if self.churn > 0 else 0.0
        return {
            'expected_lifespan_months': round(expected_lifespan_months, 1),
            'clv_undiscounted': round(clv_simple, 2)
        }
        
    def calculate_dcf_clv_closed_form(self):
        # Exact closed-form: Margin * (1 / (1 + d - r))
        denominator = 1.0 + self.monthly_discount - self.retention
        clv_dcf = (self.margin / denominator) if denominator > 0 else 0.0
        return round(clv_dcf, 2)
        
    def calculate_finite_horizon_dcf_clv(self, months=36):
        # Sum of discounted cash flows over finite horizon
        cum_clv = 0.0
        active_prob = 1.0
        for t in range(1, months + 1):
            discount_factor = 1.0 / ((1.0 + self.monthly_discount) ** t)
            expected_cash_flow = self.margin * active_prob
            discounted_cf = expected_cash_flow * discount_factor
            cum_clv += discounted_cf
            active_prob *= self.retention # decay
        return round(cum_clv, 2)

