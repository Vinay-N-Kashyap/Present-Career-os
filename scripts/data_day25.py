        for m_birth in range(1, months + 1):
            cohort_customers = int(round(self.init_size * ((1.0 + self.cohort_growth) ** (m_birth - 1))))
            cohort_cac_spend = cohort_customers * self.cac
            total_acquisition_spend += cohort_cac_spend
            
            # Track cohort revenue through remaining months
            active_mrr = cohort_customers * self.arpu
            cohort_history = []
            
            for m_current in range(m_birth, months + 1):
                gross_profit = active_mrr * self.gm
                idx = m_current - 1
                portfolio_monthly_rev[idx] += active_mrr
                portfolio_monthly_gp[idx] += gross_profit
                
