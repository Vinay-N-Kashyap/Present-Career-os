    def run_simulation(self, months=36):
        cohorts = []
        portfolio_monthly_rev = [0.0] * months
        portfolio_monthly_gp = [0.0] * months
        total_acquisition_spend = 0.0
        total_discounted_gross_profit = 0.0
        
