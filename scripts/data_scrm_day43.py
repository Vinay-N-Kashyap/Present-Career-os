class SaasRetentionEconomicsEngine:
    """Computes exact Gross Revenue Retention (GRR), Net Revenue Retention (NRR), and Quick Ratios."""
    def __init__(self):
        pass

    def evaluate_cohort_retention(self, cohort_name, starting_arr, expansion_arr, contraction_arr, churned_arr, new_arr=0.0):
        """Calculate standard SaaS retention metrics with strict boundary checks."""
        assert starting_arr > 0, "Starting ARR must be strictly positive"
        assert expansion_arr >= 0, "Expansion ARR cannot be negative"
        assert contraction_arr >= 0, "Contraction ARR cannot be negative"
        assert churned_arr >= 0, "Churned ARR cannot be negative"
        assert contraction_arr + churned_arr <= starting_arr, "Contraction + Churn cannot exceed Starting ARR"

        # 1. Ending ARR from initial cohort
        retained_arr = starting_arr - contraction_arr - churned_arr
        ending_cohort_arr = retained_arr + expansion_arr
        net_change = ending_cohort_arr - starting_arr

        # 2. Gross Revenue Retention (GRR) - capped at 100%
        grr = (retained_arr / starting_arr) * 100.0

        # 3. Net Revenue Retention (NRR) - can exceed 100%
        nrr = (ending_cohort_arr / starting_arr) * 100.0

        # 4. SaaS Quick Ratio
        churn_drag = contraction_arr + churned_arr
        quick_ratio = ((new_arr + expansion_arr) / churn_drag) if churn_drag > 0 else float("inf")

        return {
            "cohort_name": cohort_name,
            "starting_arr_usd": round(starting_arr, 2),
            "retained_arr_usd": round(retained_arr, 2),
            "expansion_arr_usd": round(expansion_arr, 2),
            "contraction_arr_usd": round(contraction_arr, 2),
            "churned_arr_usd": round(churned_arr, 2),
            "ending_cohort_arr_usd": round(ending_cohort_arr, 2),
            "net_arr_delta_usd": round(net_change, 2),
            "grr_percentage": round(grr, 2),
            "nrr_percentage": round(nrr, 2),
            "quick_ratio": round(quick_ratio, 2) if quick_ratio != float("inf") else "INF_NO_CHURN",
            "valuation_health_tier": "TOP_DECILE_ELITE" if nrr >= 125 and grr >= 92 else (
                "HEALTHY_EXPANDING" if nrr >= 110 and grr >= 85 else "TROUBLED_LEAKY_BUCKET"
            )
        }

