p2_code = """# Pure Python K-Means Clustering Algorithm from scratch
import math
import random

def euclidean(p1, p2):
    return math.sqrt(sum((a - b)**2 for a, b in zip(p1, p2)))

def run_kmeans(points, k, max_iters=25, seed=42):
    random.seed(seed)
    # K-Means++ initialization
    centroids = [random.choice(points)]
    for _ in range(1, k):
        dists = [min(euclidean(p, c)**2 for c in centroids) for p in points]
        total_d = sum(dists)
        probs = [d / total_d for d in dists]
        r = random.random()
        cum = 0.0
        for idx, p in enumerate(probs):
            cum += p
            if cum >= r:
                centroids.append(points[idx])
                break
                
    for iteration in range(max_iters):
        # Expectation: assign points to nearest centroid
        clusters = [[] for _ in range(k)]
        for p in points:
            nearest_idx = min(range(k), key=lambda c_idx: euclidean(p, centroids[c_idx]))
            clusters[nearest_idx].append(p)
            
        # Maximization: recompute centroids
        new_centroids = []
        for c_idx in range(k):
            if clusters[c_idx]:
                dim = len(points[0])
                mean_pt = [sum(pt[d] for pt in clusters[c_idx]) / len(clusters[c_idx]) for d in range(dim)]
                new_centroids.append(mean_pt)
            else:
                new_centroids.append(centroids[c_idx])
                
        # Check convergence
        shift = sum(euclidean(c1, c2) for c1, c2 in zip(centroids, new_centroids))
        centroids = new_centroids
        if shift < 1e-4:
            break
            
    # Calculate Within-Cluster Sum of Squares (Inertia)
    wcss = 0.0
    for c_idx, cluster in enumerate(clusters):
        for p in cluster:
            wcss += euclidean(p, centroids[c_idx])**2
    return centroids, clusters, wcss, iteration + 1

# 30 Synthetic standardized customer behavioral data points
random.seed(101)
cluster_a = [[random.gauss(-2.0, 0.5), random.gauss(-2.0, 0.5)] for _ in range(15)]
cluster_b = [[random.gauss(2.0, 0.5), random.gauss(2.0, 0.5)] for _ in range(15)]
dataset = cluster_a + cluster_b

centroids, clusters, wcss, iters = run_kmeans(dataset, k=2)
print(f"K-Means Algorithm Converged in {iters} iterations")
print(f"Total Within-Cluster Sum of Squares (Inertia): {wcss:.2f}")
print("Discovered Centroids:")
for idx, c in enumerate(centroids):
    print(f"  Cluster {idx+1}: [{c[0]:.2f}, {c[1]:.2f}] (Count: {len(clusters[idx])})")
"""

